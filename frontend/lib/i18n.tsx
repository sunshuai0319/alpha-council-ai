export function getInitialLocale(savedLocale: string | null): Locale {
  return savedLocale === "en-US" ? "en-US" : "zh-CN"
}

export function translate(locale: Locale, key: MessageKey, values?: Record<string, string | number>) {
  const template = messages[locale][key] ?? messages["en-US"][key] ?? key
  return values ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`)) : template
}

type I18nContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: MessageKey, values?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("zh-CN")

  useEffect(() => {
    setLocaleState(getInitialLocale(window.localStorage.getItem("alpha-council-locale")))
  }, [])

  useEffect(() => {
    window.localStorage.setItem("alpha-council-locale", locale)
    document.documentElement.lang = locale === "zh-CN" ? "zh-CN" : "en"
  }, [locale])

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale: (nextLocale) => setLocaleState(nextLocale),
    t: (key, values) => translate(locale, key, values),
  }), [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  return context ?? {
    locale: "zh-CN" as Locale,
    setLocale: () => undefined,
    t: (key: MessageKey, values?: Record<string, string | number>) => translate("zh-CN", key, values),
  }
}
